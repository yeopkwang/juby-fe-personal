import { useEffect } from 'react'

/** 항상 뒤에 붙는 꼬리. 탭이 여러 개일 때 어느 것이 이 앱인지 알아보게 한다 */
const SITE = 'JUBY'

/**
 * 이 화면이 열려 있는 동안의 브라우저 탭 제목.
 *
 * 예전에는 index.html의 `<title>JUBY</title>` 하나가 전부라 **모든 화면이 같은
 * 제목**이었다. 종목 두세 개를 탭으로 벌려 놓고 비교하는 것이 이 앱의 흔한 사용법인데,
 * 그때 탭이 전부 'JUBY'라 어느 것이 삼성전자인지 눌러 보기 전에는 알 수 없었다.
 * 즐겨찾기와 방문 기록에 남는 이름도 마찬가지였다.
 *
 * `null`을 넘기면 꼬리만 남는다. 홈이 그 경우다 — 'JUBY · JUBY'가 될 이유가 없다.
 *
 * ⚠️ **되돌리는 뒷정리를 일부러 넣지 않았다.** 화면을 떠날 때 'JUBY'로 되돌리면
 * 다음 화면이 자기 제목을 적기 전 찰나에 제목이 한 번 깜빡인다. 대신 **모든 라우트가
 * 이 훅을 부른다**는 약속으로 푼다(App.tsx의 `path="*"`까지 포함). 라우트를 새로
 * 만들면서 이 훅을 빠뜨리면 앞 화면의 제목이 그대로 남으니, 그때는 새 화면에
 * 한 줄을 더하면 된다.
 *
 * 마이페이지처럼 껍데기와 내용이 나뉜 곳은 **안쪽(자식 라우트)만** 부른다.
 * 양쪽이 다 부르면 자식 effect가 먼저 돌고 부모가 덮어써서, 어느 탭을 열든
 * 제목이 '마이페이지'로 같아진다.
 */
export function useDocumentTitle(title: string | null): void {
  useEffect(() => {
    document.title = title === null ? SITE : `${title} · ${SITE}`
  }, [title])
}
